const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const repo = path.resolve(__dirname, '../..');
const cli = 'C:/Users/bethh/AppData/Local/npm-cache/_npx/6bc7bae5c2059953/node_modules/eas-cli/bin/run';
const buildId = 'bc75c794-1646-4a98-85b7-38c2073fd009';
const profile = JSON.parse(fs.readFileSync(path.join(repo, 'mobile/eas.json'), 'utf8')).submit['play-alpha-draft'].android;
if (profile.applicationId !== 'com.recipereborn.app' || profile.track !== 'alpha' || profile.releaseStatus !== 'draft' || profile.changesNotSentForReview !== true) throw Error('Draft-only guard failed');
const proof = JSON.parse(fs.readFileSync(path.join(repo, 'outputs/releases/android-code-14-play-artifact-verification.json'), 'utf8').replace(/^\uFEFF/, ''));
if (proof.buildId !== buildId || crypto.createHash('sha256').update(fs.readFileSync(proof.file)).digest('hex').toUpperCase() !== proof.sha256) throw Error('Artifact guard failed');
const remote = JSON.parse(fs.readFileSync(path.join(__dirname, 'code-14-fresh-build-check.json'), 'utf8'));
if (remote.id !== buildId || remote.status !== 'FINISHED' || Date.now() - Date.parse(remote.checkedAt) > 600000) throw Error('Fresh remote candidate proof required');
const requestPath = path.join(__dirname, 'code-14-draft-upload-request.json');
const request = { requestedAt: new Date().toISOString(), buildId, profile: 'play-alpha-draft', androidConfig: profile, sourceCommit: proof.gitCommitHash, sha256: proof.sha256, authorization: 'User-authorized Play testing; root delegated this exact code14 alpha draft upload only, with changesNotSentForReview:true. No review request, rollout, purchase, new build or credential change.' };
fs.writeFileSync(requestPath, JSON.stringify(request, null, 2) + '\n', { flag: 'wx' });
const args = [cli, 'submit', '--platform', 'android', '--profile', 'play-alpha-draft', '--id', buildId, '--non-interactive', '--no-wait'];
const out = fs.openSync(path.join(__dirname, 'code-14-draft-upload.stdout.log'), 'wx');
const err = fs.openSync(path.join(__dirname, 'code-14-draft-upload.stderr.log'), 'wx');
const child = spawn(process.execPath, args, { cwd: path.join(repo, 'mobile'), windowsHide: true, stdio: ['ignore', out, err] });
child.on('error', (error) => { console.error('Submit process error:', error.message); process.exitCode = 1; });
child.on('close', (code) => {
  fs.closeSync(out); fs.closeSync(err);
  const stdout = fs.readFileSync(path.join(__dirname, 'code-14-draft-upload.stdout.log'), 'utf8');
  const ids = [...stdout.matchAll(/\/submissions\/([0-9a-f-]{36})/g)].map(match => match[1]);
  const result = { finishedAt: new Date().toISOString(), exitCode: code, submissionIds: [...new Set(ids)], logs: ['code-14-draft-upload.stdout.log', 'code-14-draft-upload.stderr.log'], noAutomaticRetry: true };
  fs.writeFileSync(path.join(__dirname, 'code-14-draft-upload-launch.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result, null, 2));
  process.exitCode = code || 0;
});
